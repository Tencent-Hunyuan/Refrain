#!/usr/bin/env python3
"""Build all real-video SDC calibration cells from deduplicated array caches.

Without --run, report inventory and memory estimates only. Each completed cell
is an atomic mmap directory and is reused only for the identical cache and
partition. No source video is decoded or generated by this tool.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import json
import os
import resource
import shutil
import sys
import time
import uuid
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from evaluation.style_consistency.bank.array_bank import ArrayConditionalResidualStyleBank

DEFAULT = ROOT / "weights/sdc_full_bank"
DEFAULT_CACHE = ROOT / "outputs/calibration_cache"
BANK_ID = "full_real_csd_STYLE_3env_5fold_20260923"
SEED, GROUPS, FOLDS = 20260908, 3, 5
ALGORITHM = "conditional_residual_v5_exact_array_v1"


def atomic_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp")
    temp.write_text(json.dumps(data, indent=2, allow_nan=False) + "\n")
    os.replace(temp, path)


def cache_array(cache, manifest, name):
    spec = manifest.get("array_files", {}).get(name, {})
    if isinstance(spec, str):
        filename = spec
    else:
        filename = spec.get("file", f"{name}.npy")
    return np.load(Path(cache) / filename, mmap_mode="r", allow_pickle=False)


def cache_inventory(cache):
    cache = Path(cache)
    meta = json.loads((cache / "manifest.json").read_text())
    if meta.get("schema_version") != 1:
        raise RuntimeError("unsupported energy-cache schema")
    review = meta.get("duplicate_review")
    needs_review = meta.get("duplicate_conflicts", 0) or meta.get("duplicate_requires_review", 0)
    if (review is not None and not review.get("allowed_for_bank", False)) or (needs_review and review is None):
        raise RuntimeError("energy-cache duplicate differences require a recorded source/sampling review")
    nv, ns = int(meta["n_videos"]), int(meta["n_splits"])
    offsets = cache_array(cache, meta, "video_offsets")
    md5 = cache_array(cache, meta, "md5")
    if offsets.shape != (nv + 1,) or int(offsets[0]) != 0 or int(offsets[-1]) != ns:
        raise RuntimeError("video/split offsets do not match cache inventory")
    if np.any(np.diff(offsets) <= 0) or md5.shape != (nv,) or md5.dtype != np.dtype("S32"):
        raise RuntimeError("invalid usable-video inventory")
    for name in ("content", "csd", "vgg", "video_idx", "splits_in_shot"):
        if cache_array(cache, meta, name).shape != (ns,):
            raise RuntimeError(f"split array has wrong size: {name}")
    if cache_array(cache, meta, "shot_count").shape != (nv,):
        raise RuntimeError("shot_count does not match video inventory")
    return meta


def ensure_partition(cache, output, manifest):
    output = Path(output)
    path = output / "partition"
    if path.exists():
        meta = json.loads((path / "metadata.json").read_text())
        expected = (SEED, GROUPS, FOLDS, int(manifest["n_videos"]))
        actual = (meta["seed"], meta["groups"], meta["folds"], meta["n_videos"])
        if actual != expected or not meta.get("complete"):
            raise RuntimeError("existing source partition belongs to a different cache/protocol")
        return path
    nv = int(manifest["n_videos"])
    md5 = cache_array(cache, manifest, "md5")
    sorter = np.argsort(md5, kind="mergesort")
    sorted_md5 = md5[sorter]
    if np.any(sorted_md5[1:] == sorted_md5[:-1]) or np.any(sorted_md5 == b""):
        raise RuntimeError("full bank must contain unique nonempty source MD5s")
    del sorted_md5
    permutation = np.arange(nv, dtype=np.int64)
    np.random.default_rng(SEED).shuffle(permutation)
    group, fold = np.empty(nv, dtype=np.uint8), np.empty(nv, dtype=np.uint8)
    group[permutation] = np.arange(nv, dtype=np.int64) % GROUPS
    fold[permutation] = np.arange(nv, dtype=np.int64) % FOLDS
    temp = output / f".partition.tmp.{os.getpid()}.{uuid.uuid4().hex}"
    temp.mkdir(parents=True)
    try:
        for name, arr in (("md5", md5), ("md5_sorter", sorter), ("permutation", permutation),
                          ("group", group), ("fold", fold)):
            np.save(temp / f"{name}.npy", arr, allow_pickle=False)
        metadata = {"complete": True, "seed": SEED, "groups": GROUPS, "folds": FOLDS,
                    "n_videos": nv,
                    "rule": "fixed shuffle of merged unique-video order; group=i%3, fold=i%5",
                    "group_sizes": np.bincount(group, minlength=GROUPS).tolist(),
                    "fold_sizes": np.bincount(fold, minlength=FOLDS).tolist()}
        (temp / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
        os.rename(temp, path)
    except BaseException:
        shutil.rmtree(temp)
        raise
    return path


class SourceFoldLookup:
    """Sorted source identity lookup; no case-order substitution."""

    def __init__(self, path=DEFAULT):
        path = Path(path) / "partition"
        # Read these compact arrays sequentially before the shuffled lookup.
        # Fancy indexing a cold NFS-backed mmap otherwise causes thousands of
        # remote page faults even though the final sorted arrays fit in RAM.
        self.md5 = np.load(path / "md5.npy", allow_pickle=False)
        self.sorter = np.load(path / "md5_sorter.npy", allow_pickle=False)
        self.folds = np.load(path / "fold.npy", allow_pickle=False)
        # About 71 MB for the full corpus, loaded once. Direct sorted lookup
        # avoids repeatedly validating a two-million-entry sorter and random
        # reads through network-backed memory maps for each query source.
        self.sorted_md5 = np.asarray(self.md5[self.sorter])
        self.sorted_folds = np.asarray(self.folds[self.sorter])

    def get(self, source_md5, default=None):
        key = bytes(source_md5) if isinstance(source_md5, (bytes, np.bytes_)) else str(source_md5).encode("ascii")
        if not 1 <= len(key) <= 32:
            return default
        pos = int(np.searchsorted(self.sorted_md5, np.asarray(key, dtype="S32")))
        if pos == len(self.md5):
            return default
        return int(self.sorted_folds[pos]) if self.sorted_md5[pos] == key else default

    def __contains__(self, source_md5):
        return self.get(source_md5) is not None

    def __getitem__(self, source_md5):
        value = self.get(source_md5)
        if value is None:
            raise KeyError(source_md5)
        return value

    def __len__(self):
        return len(self.md5)

    def as_dict(self):
        return {value.decode("ascii"): int(fold) for value, fold in zip(self.md5, self.folds)}


def load_source_folds(path=DEFAULT, as_lookup=False):
    lookup = SourceFoldLookup(path)
    return lookup if as_lookup else lookup.as_dict()


def cell_name(head, fold, group):
    return f"{head}_fold{fold}_group{group}"


def fit_cell(cache, output, head, fold, group):
    cache, output = Path(cache), Path(output)
    name = cell_name(head, fold, group)
    destination = output / "cells" / name
    expected = {"algorithm": ALGORITHM, "bank_id": BANK_ID,
                "head": head, "fold": fold, "group": group, "seed": SEED}
    if destination.exists():
        bank = ArrayConditionalResidualStyleBank.load(destination)
        if any(bank.provenance.get(k) != v for k, v in expected.items()):
            raise RuntimeError(f"refusing to reuse stale cell: {name}")
        print(json.dumps({"cell": name, "event": "reused", "kappa": bank.kappa}), flush=True)
        return {**bank.provenance, "reused": True, "kappa": bank.kappa,
                "content_bins": bank.content_bins, "path": str(destination.relative_to(output))}
    log = output / "logs" / f"{name}.jsonl"
    log.parent.mkdir(parents=True, exist_ok=True)
    start = time.monotonic()

    def progress(event, **values):
        row = {"cell": name, "event": event, "seconds": round(time.monotonic() - start, 3), **values}
        with log.open("a") as f:
            f.write(json.dumps(row, allow_nan=False) + "\n")
        print(json.dumps(row, allow_nan=False), flush=True)

    manifest = json.loads((cache / "manifest.json").read_text())
    partition = output / "partition"
    permutation = np.load(partition / "permutation.npy", mmap_mode="r", allow_pickle=False)
    groups = np.load(partition / "group.npy", mmap_mode="r", allow_pickle=False)
    folds = np.load(partition / "fold.npy", mmap_mode="r", allow_pickle=False)
    selected = permutation[(groups[permutation] == group) & (folds[permutation] != fold)]
    nv = len(selected)
    offsets = cache_array(cache, manifest, "video_offsets")
    lengths = offsets[selected + 1] - offsets[selected]
    dest = np.concatenate((np.zeros(1, dtype=np.int64), np.cumsum(lengths)))
    ns = int(dest[-1])
    progress("gather_start", videos=nv, splits=ns)
    # Gather in shuffled-video order, exactly as N02's per-video list traversal.
    indices = np.arange(ns, dtype=np.int64)
    indices += np.repeat(offsets[selected] - dest[:-1], lengths)
    content = np.asarray(cache_array(cache, manifest, "content")[indices], dtype=np.float64)
    style = np.asarray(cache_array(cache, manifest, head)[indices], dtype=np.float64)
    video_idx = cache_array(cache, manifest, "video_idx")[indices]
    shot_count = cache_array(cache, manifest, "shot_count")[video_idx]
    split_count = cache_array(cache, manifest, "splits_in_shot")[indices]
    if np.any(shot_count == 0) or np.any(split_count == 0):
        raise RuntimeError("hierarchical counts must be positive")
    weights = (1.0 / nv) / shot_count / split_count
    del indices, video_idx, shot_count, split_count, selected, lengths, dest
    progress("fit_start", videos=nv, splits=ns)
    bank = ArrayConditionalResidualStyleBank.fit(content, style, weights, progress=progress)
    provenance = {**expected, "videos": nv, "splits": ns,
                  "cache_manifest": str(cache / "manifest.json"),
                  "huber_iterations": bank.huber_iterations,
                  "fit_seconds": time.monotonic() - start,
                  "peak_rss_kib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss}
    bank.save(destination, provenance=provenance)
    progress("saved", kappa=bank.kappa, path=str(destination), peak_rss_kib=provenance["peak_rss_kib"])
    return {**provenance, "reused": False, "kappa": bank.kappa, "content_bins": bank.content_bins,
            "path": str(destination.relative_to(output))}


def load_bank_set(path=DEFAULT, mmap_mode="r"):
    path = Path(path)
    inventory = json.loads((path / "bank_inventory.json").read_text())
    if not inventory.get("complete") or len(inventory["cells"]) != 2 * GROUPS * FOLDS:
        raise RuntimeError("full real bank is not complete")
    def load_cell(cell):
        head, fold, group = cell["head"], int(cell["fold"]), int(cell["group"])
        bank = ArrayConditionalResidualStyleBank.load(path / cell["path"], mmap_mode=mmap_mode)
        return (head, fold, f"real_env{group}"), bank

    if mmap_mode is None:
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            banks = dict(pool.map(load_cell, inventory["cells"]))
    else:
        banks = dict(map(load_cell, inventory["cells"]))
    return banks, inventory


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE)
    parser.add_argument("--output", type=Path, default=DEFAULT)
    parser.add_argument("--run", action="store_true", help="fit/reuse selected cells after reporting inventory")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--cell", action="append", help="one cell as csd:fold:group or vgg:fold:group")
    parser.add_argument("--max-cells", type=int)
    parser.add_argument("--finalize-only", action="store_true",
                        help="assemble the inventory from completed cell metadata without refitting")
    args = parser.parse_args()
    if not 1 <= args.workers <= 32:
        parser.error("workers must be between 1 and 32")
    manifest = cache_inventory(args.cache)
    cells = [(h, f, g) for h in ("csd", "vgg") for f in range(FOLDS) for g in range(GROUPS)]
    if args.cell:
        cells = [(v[0], int(v[1]), int(v[2])) for v in (s.split(":") for s in args.cell)]
        if any(h not in ("csd", "vgg") or f not in range(FOLDS) or g not in range(GROUPS)
               for h, f, g in cells) or len(set(cells)) != len(cells):
            parser.error("invalid or duplicate cell selection")
    if args.max_cells is not None:
        if args.max_cells < 1:
            parser.error("max-cells must be positive")
        cells = cells[:args.max_cells]
    expected_ns = int(manifest["n_splits"]) * (FOLDS - 1) / (FOLDS * GROUPS)
    print(json.dumps({"bank_id": BANK_ID, "cache_videos": manifest["n_videos"],
                      "cache_splits": manifest["n_splits"], "cells_selected": len(cells),
                      "workers": args.workers, "run": args.run, "finalize_only": args.finalize_only,
                      "estimated_splits_per_cell": int(expected_ns),
                      "estimated_peak_worker_gib": expected_ns * 200 / 2**30,
                      "estimated_all_cells_disk_gib": expected_ns * 32 * 30 / 2**30}, indent=2), flush=True)
    if not args.run:
        return
    args.output.mkdir(parents=True, exist_ok=True)
    ensure_partition(args.cache, args.output, manifest)
    if args.finalize_only:
        pass
    elif args.workers == 1:
        for head, fold, group in cells:
            fit_cell(args.cache, args.output, head, fold, group)
    else:
        with concurrent.futures.ProcessPoolExecutor(max_workers=args.workers) as pool:
            futures = [pool.submit(fit_cell, str(args.cache), str(args.output), h, f, g)
                       for h, f, g in cells]
            for future in concurrent.futures.as_completed(futures):
                future.result()
    inventory = []
    for head in ("csd", "vgg"):
        for fold in range(FOLDS):
            for group in range(GROUPS):
                path = args.output / "cells" / cell_name(head, fold, group)
                if not (path / "metadata.json").exists():
                    continue
                metadata = json.loads((path / "metadata.json").read_text())
                if metadata.get("format") != "sdc_conditional_array_bank_v1" or not metadata.get("complete"):
                    raise RuntimeError("cell metadata is incomplete or unsupported")
                provenance = metadata["provenance"]
                if (provenance["head"], provenance["fold"], provenance["group"]) != (head, fold, group):
                    raise RuntimeError("cell identity does not match its directory")
                inventory.append({**provenance, "kappa": metadata["scalars"]["kappa"],
                                  "content_bins": metadata["arrays"]["content_edges"]["shape"][0] - 1,
                                  "path": str(path.relative_to(args.output))})
    result = {"bank_id": BANK_ID, "algorithm": ALGORITHM, "csd_head": "module.last_layer_style",
              "n_videos": int(manifest["n_videos"]), "n_splits": int(manifest["n_splits"]),
              "usable_source_videos": int(manifest["n_videos"]),
              "raw_cache_inventory": {key: manifest[key] for key in
                                      ("n_videos", "n_splits", "sources", "duplicate_videos",
                                       "duplicate_conflicts", "duplicate_requires_review", "duplicate_review") if key in manifest},
              "seed": SEED, "groups": GROUPS, "folds": FOLDS,
              "complete": len(inventory) == 30, "cells": inventory}
    atomic_json(args.output / "bank_inventory.json", result)
    print(json.dumps({"event": "inventory_saved", "cells": len(inventory),
                      "complete": result["complete"]}), flush=True)


if __name__ == "__main__":
    main()
